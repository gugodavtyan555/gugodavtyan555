"""Packs ../site into one Cloudflare Worker script (worker/worker.js).

The whole shop is ~1 MB, well under the free Worker size limit, so it is
served straight from memory with no separate asset upload.
"""
import base64
import json
import mimetypes
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "site"
OUT = ROOT / "worker" / "worker.js"

TEXT = {".html", ".xml", ".txt", ".css", ".js", ".json", ".svg"}


def main():
    files = {}
    for f in sorted(SITE.rglob("*")):
        if not f.is_file():
            continue
        rel = "/" + f.relative_to(SITE).as_posix()
        ctype = mimetypes.guess_type(f.name)[0] or "application/octet-stream"
        if f.suffix in TEXT:
            files[rel] = {"t": ctype + "; charset=utf-8", "s": f.read_text()}
        else:
            files[rel] = {"t": ctype, "b": base64.b64encode(f.read_bytes()).decode()}
    js = f"""// Generated by generators/build_worker.py from ../site. Do not edit by hand.
const FILES = {json.dumps(files)};
const cache = new Map();
function body(f) {{
  if (f.s !== undefined) return f.s;
  if (!cache.has(f.b)) cache.set(f.b, Uint8Array.from(atob(f.b), (c) => c.charCodeAt(0)));
  return cache.get(f.b);
}}
export default {{
  async fetch(request) {{
    const url = new URL(request.url);
    let p = decodeURIComponent(url.pathname);
    if (p.endsWith('/')) p += 'index.html';
    let f = FILES[p] || FILES[p + '.html'] || FILES[p + '/index.html'];
    const status = f ? 200 : 404;
    f = f || FILES['/404.html'];
    const long = /\\.(png|jpg|svg|webp)$/.test(p);
    return new Response(request.method === 'HEAD' ? null : body(f), {{
      status,
      headers: {{
        'content-type': f.t,
        'cache-control': long ? 'public, max-age=86400' : 'public, max-age=300',
        'x-content-type-options': 'nosniff',
      }},
    }});
  }},
}};
"""
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(js)
    print(f"packed {len(files)} files into {OUT} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
